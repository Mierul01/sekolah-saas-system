export function getTranslator(lang) {
  const dict = translations[lang] || translations.ms
  return function t(path, vars) {
    const parts = path.split('.')
    let node = dict
    for (const p of parts) {
      node = node?.[p]
      if (node === undefined) break
    }
    if (node === undefined) return path
    if (typeof node === 'string' && vars) {
      return Object.entries(vars).reduce((str, [k, v]) => str.replaceAll(`{${k}}`, v), node)
    }
    return node
  }
}
